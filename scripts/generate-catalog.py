#!/usr/bin/env python3
"""Generate resource names and verbs from a pinned public Microsoft reference."""
import argparse
import io
import json
from pathlib import Path
import re
import tarfile
import urllib.request

SOURCE_COMMIT = 'd6b0925033cc5d8e29e15fbb425fe22b9ac6a038'
ROOT = Path(__file__).resolve().parents[1]


def documents(source_dir):
    if source_dir:
        return [(path.name, path.read_text()) for path in Path(source_dir).glob('*_ref.md')]
    url = f'https://codeload.github.com/OfficeDev/skype-docs/tar.gz/{SOURCE_COMMIT}'
    with urllib.request.urlopen(url, timeout=60) as response:
        archive = response.read()
    result = []
    with tarfile.open(fileobj=io.BytesIO(archive), mode='r:gz') as stream:
        for entry in stream:
            if entry.isfile() and '/Skype/UCWA/' in entry.name and entry.name.endswith('_ref.md'):
                result.append((Path(entry.name).name, stream.extractfile(entry).read().decode()))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', help='Existing Skype/UCWA directory from the pinned reference')
    args = parser.parse_args()
    records = []
    for filename, content in sorted(documents(args.source_dir)):
        # *_ref.md also includes enum/struct pages, which are not HTTP resources.
        if not re.search(r'^##\s+Web Link\s*$', content, re.MULTILINE):
            continue
        heading = re.search(r'^#\s+(.+)$', content, re.MULTILINE)
        if not heading:
            raise ValueError(f'Missing resource title in {filename}')
        relation = re.sub(r'\s+reference(?:\s+for\s+.*)?$', '', heading[1].strip(), flags=re.IGNORECASE)
        identifier = filename.removesuffix('_ref.md')
        methods = list(dict.fromkeys(re.findall(r'^###\s+(GET|POST|PUT|PATCH|DELETE|OPTIONS|HEAD)\s*$', content, re.MULTILINE)))
        if not re.fullmatch(r'[a-zA-Z][a-zA-Z0-9]*', relation):
            raise ValueError(f'Unexpected resource relation {relation!r} in {filename}')
        records.append({
            'id': identifier,
            'name': relation,
            'methods': methods,
            'documentationUrl': f'https://learn.microsoft.com/en-us/skype-sdk/ucwa/{identifier.lower()}_ref',
        })
    if not records:
        raise ValueError('No public UCWA resource reference files were found')
    header = f'''// Generated by scripts/generate-catalog.py. Do not edit by hand.
// Source: OfficeDev/skype-docs, commit {SOURCE_COMMIT}.
// Metadata only: resource names, declared HTTP verbs, and documentation links.

export interface UcwaResourceDocumentation {{
  /** Reference page identifier; numbered pages can describe context-specific variants. */
  id: string;
  /** Public reference page name; numbered names may be context-specific variants. */
  name: string;
  methods: readonly string[];
  documentationUrl: string;
}}

/** Public reference coverage; runtime availability still comes from server links. */
export const UCWA_RESOURCE_CATALOG = '''
    footer = ''' as const satisfies readonly UcwaResourceDocumentation[];

export type DocumentedUcwaResourceName = typeof UCWA_RESOURCE_CATALOG[number]['name'];

/** Find documentation by reference resource name or page ID (case-sensitive). */
export function resourceDocumentation(name: string): readonly UcwaResourceDocumentation[] {
  return UCWA_RESOURCE_CATALOG.filter((resource) => resource.name === name || resource.id === name);
}
'''
    (ROOT / 'src/catalog.ts').write_text(header + json.dumps(records, indent=2) + footer)
    summary = {
        'referenceCommit': SOURCE_COMMIT,
        'referencePages': len(records),
        'uniqueResourceNames': len({record['name'] for record in records}),
        'referenceMethods': sum(len(record['methods']) for record in records),
        'caveat': 'Public resource reference coverage only; no private extensions or native media implementation.',
    }
    (ROOT / 'docs/resource-catalog.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
