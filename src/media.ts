export const nativeSharingCapabilityRelations = ['startApplicationSharing', 'addApplicationSharing', 'stopApplicationSharing'] as const;

/** These are advertised relations, not a guarantee that a host media engine implements them. */
export const mediaCapabilityRelations = [
  'startAudio', 'startVideo', 'startAudioVideo', 'addAudio', 'addVideo', 'addAudioVideo',
  'stopAudio', 'stopVideo', 'stopAudioVideo', 'acceptWithAnswer', 'sendProvisionalAnswer',
  'decline', 'cancel', 'muteAudio', 'unmuteAudio', 'muteVideo', 'unmuteVideo',
  'audioVideo', 'audioVideoSession', 'audioVideoNegotiation', 'audioVideoPolicies',
  'applicationSharing', 'applicationSharer', 'participantAudio', 'participantVideo',
  'participantApplicationSharing', 'mediaPolicies', 'mediaRelayAccessToken',
  ...nativeSharingCapabilityRelations,
] as const;

export type MediaCapabilityRelation = typeof mediaCapabilityRelations[number];
export type MediaCapabilities = Readonly<Record<MediaCapabilityRelation, boolean>>;

const offerFields = {
  startAudio: ['to', 'importance', 'subject', 'threadId', 'joinAudioMuted'],
  startVideo: ['to', 'importance', 'subject', 'threadId', 'joinVideoMuted'],
  startAudioVideo: ['to', 'importance', 'subject', 'threadId', 'joinAudioMuted', 'joinVideoMuted'],
  addAudio: ['to', 'joinAudioMuted'],
  addVideo: ['to', 'joinVideoMuted'],
  addAudioVideo: ['to', 'joinAudioMuted', 'joinVideoMuted'],
  startApplicationSharing: ['to', 'importance', 'subject', 'threadId', 'telemetryId'],
  addApplicationSharing: ['telemetryId'],
} as const;

function boundedString(value: string, name: string, max: number): void {
  if (typeof value !== 'string' || value.trim().length === 0 || value.length > max) {
    throw new TypeError(`${name} must contain 1 to ${max} characters.`);
  }
}

function requireSdp(value: string): void {
  if (typeof value !== 'string' || value.trim().length === 0) throw new TypeError('SDP must not be empty.');
}

/** Encode SDP locally; offers are external resources in UCWA JSON rather than JSON string properties. */
export function encodeSdpDataUri(sdp: string): string {
  requireSdp(sdp);
  let binary = '';
  for (const byte of new TextEncoder().encode(sdp)) binary += String.fromCharCode(byte);
  return `data:application/sdp;base64,${globalThis.btoa(binary)}`;
}

/** Only inline application/sdp data is decoded. This helper never fetches an external URL. */
export function decodeSdpDataUri(uri: string): string {
  const match = /^data:application\/sdp(?:;charset=(?:utf-8|us-ascii))?(;base64)?,([\s\S]*)$/i.exec(uri);
  if (!match) throw new ProtocolError('The media description must be an inline application/sdp data URI.');
  try {
    const payload = decodeURIComponent(match[2]!);
    const sdp = match[1]
      ? new TextDecoder('utf-8', { fatal: true }).decode(Uint8Array.from(globalThis.atob(payload), (char) => char.charCodeAt(0)))
      : payload;
    requireSdp(sdp);
    return sdp;
  } catch {
    throw new ProtocolError('The inline SDP media description is empty or has invalid encoding.');
  }
}

/** Extract an advertised SDP offer/answer without sending it through the authenticated HTTP transport. */
export function mediaDescription(resource: ResourceReference, relation: SdpRelation): string {
  return decodeSdpDataUri(getLink(resource.data, relation, resource.url));
}

/**
 * Typed UCWA media signaling. HTTP success means an operation was accepted; consume the session's
 * events and a compatible media engine to establish, render and transmit audio/video or screen frames.
 */
export class SkypeForBusinessMedia {
  constructor(private readonly session: MediaSignalingSession) {}

  capabilities(resource: ResourceReference): MediaCapabilities {
    return Object.freeze(Object.fromEntries(mediaCapabilityRelations.map((relation) => [relation, hasLink(resource.data, relation)]))) as MediaCapabilities;
  }

  async communicationCapabilities(signal?: AbortSignal): Promise<MediaCapabilities> {
    return this.capabilities(await this.session.communication(signal));
  }

  private offerBody(operation: keyof typeof offerFields, options: MediaOfferOptions): UcwaResource {
    const { mediaOffer } = options;
    const supplied = options as MediaOfferOptions & Record<string, unknown>;
    const body: UcwaResource = {};
    // Structural typing permits wider option objects. Copy only fields legal for this operation.
    for (const field of offerFields[operation]) if (supplied[field] !== undefined) body[field] = supplied[field];
    const requireTarget = operation !== 'addApplicationSharing';
    if (requireTarget && (typeof body.to !== 'string' || body.to.trim().length === 0)) throw new TypeError('A target SIP URI is required.');
    if (body.subject !== undefined && (typeof body.subject !== 'string' || body.subject.length > 250)) throw new TypeError('subject must be a string of at most 250 characters.');
    const operationId = options.operationId ?? globalThis.crypto.randomUUID();
    boundedString(operationId, 'operationId', 50);
    if (options.sessionContext !== undefined) boundedString(options.sessionContext, 'sessionContext', 50);
    return {
      ...body,
      operationId,
      ...(options.sessionContext === undefined ? {} : { sessionContext: options.sessionContext }),
      ...(mediaOffer === undefined ? {} : { _links: { mediaOffer: { href: encodeSdpDataUri(mediaOffer) } } }),
    };
  }

  private async start(relation: 'startAudio' | 'startVideo' | 'startAudioVideo', options: StartCallOptions): Promise<HttpResult<AudioVideoInvitationResource>> {
    const json = this.offerBody(relation, options);
    return this.session.invoke<AudioVideoInvitationResource>(await this.session.communication(options.signal), relation, {
      method: 'POST', json, ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  startAudio(options: StartAudioOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.start('startAudio', options); }
  startVideo(options: StartVideoOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.start('startVideo', options); }
  startAudioVideo(options: StartAudioVideoOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.start('startAudioVideo', options); }

  private async add(resource: ResourceReference, relation: 'addAudio' | 'addVideo' | 'addAudioVideo', options: AddAudioVideoOptions): Promise<HttpResult<AudioVideoInvitationResource>> {
    return this.session.invoke<AudioVideoInvitationResource>(resource, relation, {
      method: 'POST', json: this.offerBody(relation, options), ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  addAudio(audioVideo: ResourceReference, options: AddAudioOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.add(audioVideo, 'addAudio', options); }
  addVideo(audioVideo: ResourceReference, options: AddVideoOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.add(audioVideo, 'addVideo', options); }
  addAudioVideo(audioVideo: ResourceReference, options: AddAudioVideoOptions): Promise<HttpResult<AudioVideoInvitationResource>> { return this.add(audioVideo, 'addAudioVideo', options); }

  /**
   * Native deployment extension: send a sharing invitation through an advertised startApplicationSharing
   * relation. POST and field names come from static native-client analysis, not a qualified live exchange.
   * A successful response does not transmit the screen; the host media engine still owns capture/transport.
   */
  async startApplicationSharing(options: StartApplicationSharingOptions): Promise<HttpResult<ApplicationSharingInvitationResource>> {
    const json = this.offerBody('startApplicationSharing', options);
    return this.session.invoke<ApplicationSharingInvitationResource>(await this.session.communication(options.signal), 'startApplicationSharing', {
      method: 'POST', json, ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  /**
   * Native deployment extension. Supply the resource that advertises addApplicationSharing.
   * Field names are established by native metadata; POST is inferred from related control operations.
   */
  async addApplicationSharing(resource: ResourceReference, options: AddApplicationSharingOptions = {}): Promise<HttpResult<ApplicationSharingInvitationResource>> {
    return this.session.invoke<ApplicationSharingInvitationResource>(resource, 'addApplicationSharing', {
      method: 'POST', json: this.offerBody('addApplicationSharing', options), ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  /** Native deployment extension; POST without a body. Stop host capture and media transport separately. */
  stopApplicationSharing(resource: ResourceReference, signal?: AbortSignal): Promise<HttpResult> {
    return this.control(resource, 'stopApplicationSharing', signal);
  }

  private async postWithQuery(resource: ResourceReference, relation: string, query: Record<string, string>, options: RequestOptions = {}): Promise<HttpResult> {
    const url = new URL(getLink(resource.data, relation, resource.url));
    for (const [key, value] of Object.entries(query)) url.searchParams.set(key, value);
    // Reuse session.invoke so its closed-session and trusted-transport checks still apply.
    return this.session.invoke({ url: resource.url, data: { _links: { [relation]: { href: url.href } } } }, relation, { ...options, method: 'POST' });
  }

  private async answer(invitation: ResourceReference, relation: 'acceptWithAnswer' | 'sendProvisionalAnswer', options: MediaAnswerOptions): Promise<HttpResult> {
    boundedString(options.sessionContext, 'sessionContext', 50);
    requireSdp(options.mediaAnswer);
    const query: Record<string, string> = { sessionContext: options.sessionContext };
    if (options.processedOfferId !== undefined) {
      boundedString(options.processedOfferId, 'processedOfferId', 100);
      query.processedOfferId = options.processedOfferId;
    }
    return this.postWithQuery(invitation, relation, query, {
      body: options.mediaAnswer,
      headers: { 'Content-Type': 'application/sdp' },
      ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  acceptWithAnswer(invitation: ResourceReference, options: MediaAnswerOptions): Promise<HttpResult> { return this.answer(invitation, 'acceptWithAnswer', options); }
  sendProvisionalAnswer(invitation: ResourceReference, options: MediaAnswerOptions): Promise<HttpResult> { return this.answer(invitation, 'sendProvisionalAnswer', options); }

  decline(invitation: ResourceReference, options: DeclineMediaOptions = {}): Promise<HttpResult> {
    return this.session.invoke(invitation, 'decline', {
      method: 'POST',
      ...(options.reason === undefined ? {} : { json: { reason: options.reason } }),
      ...(options.signal ? { signal: options.signal } : {}),
    });
  }

  cancel(invitation: ResourceReference, signal?: AbortSignal): Promise<HttpResult> {
    return this.session.invoke(invitation, 'cancel', { method: 'POST', ...(signal ? { signal } : {}) });
  }

  private stop(audioVideo: ResourceReference, relation: 'stopAudio' | 'stopVideo' | 'stopAudioVideo', options: StopMediaOptions): Promise<HttpResult> {
    return this.postWithQuery(audioVideo, relation, options.reason === undefined ? {} : { reason: options.reason }, options.signal ? { signal: options.signal } : {});
  }

  stopAudio(audioVideo: ResourceReference, options: StopMediaOptions = {}): Promise<HttpResult> { return this.stop(audioVideo, 'stopAudio', options); }
  stopVideo(audioVideo: ResourceReference, options: StopMediaOptions = {}): Promise<HttpResult> { return this.stop(audioVideo, 'stopVideo', options); }
  stopAudioVideo(audioVideo: ResourceReference, options: StopMediaOptions = {}): Promise<HttpResult> { return this.stop(audioVideo, 'stopAudioVideo', options); }

  /** Ends the local conversation through its advertised self link. */
  endConversation(conversation: ResourceReference, signal?: AbortSignal): Promise<HttpResult> {
    return this.session.invoke(conversation, 'self', { method: 'DELETE', ...(signal ? { signal } : {}) });
  }

  muteAudio(participantAudio: ResourceReference, signal?: AbortSignal): Promise<HttpResult> { return this.control(participantAudio, 'muteAudio', signal); }
  unmuteAudio(participantAudio: ResourceReference, signal?: AbortSignal): Promise<HttpResult> { return this.control(participantAudio, 'unmuteAudio', signal); }
  muteVideo(participantVideo: ResourceReference, signal?: AbortSignal): Promise<HttpResult> { return this.control(participantVideo, 'muteVideo', signal); }
  unmuteVideo(participantVideo: ResourceReference, signal?: AbortSignal): Promise<HttpResult> { return this.control(participantVideo, 'unmuteVideo', signal); }

  private control(resource: ResourceReference, relation: string, signal?: AbortSignal): Promise<HttpResult> {
    return this.session.invoke(resource, relation, { method: 'POST', ...(signal ? { signal } : {}) });
  }

  audioVideo(conversation: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<AudioVideoResource>> { return this.session.follow(conversation, 'audioVideo', signal); }
  audioVideoSession(audioVideo: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<AudioVideoSessionResource>> { return this.session.follow(audioVideo, 'audioVideoSession', signal); }
  audioVideoNegotiation(invitation: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<AudioVideoNegotiationResource>> { return this.session.follow(invitation, 'audioVideoNegotiation', signal); }
  applicationSharing(conversation: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<ApplicationSharingResource>> { return this.session.follow(conversation, 'applicationSharing', signal); }
  applicationSharer(sharing: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<ApplicationSharerResource>> { return this.session.follow(sharing, 'applicationSharer', signal); }
  participantAudio(participant: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<ParticipantAudioResource>> { return this.session.follow(participant, 'participantAudio', signal); }
  participantVideo(participant: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<ParticipantVideoResource>> { return this.session.follow(participant, 'participantVideo', signal); }
  participantApplicationSharing(participant: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<ParticipantApplicationSharingResource>> { return this.session.follow(participant, 'participantApplicationSharing', signal); }
  audioVideoPolicies(audioVideo: ResourceReference, signal?: AbortSignal): Promise<ResourceReference> { return this.session.follow(audioVideo, 'audioVideoPolicies', signal); }

  async mediaPolicies(signal?: AbortSignal): Promise<ResourceReference> { return this.session.follow(await this.session.communication(signal), 'mediaPolicies', signal); }

  /** Returns temporary relay credentials without logging or persisting them. */
  async mediaRelayAccessToken(signal?: AbortSignal): Promise<ResourceReference<MediaRelayAccessTokenResource>> {
    return this.session.follow(await this.session.communication(signal), 'mediaRelayAccessToken', signal);
  }

  mediaRelay(token: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<MediaRelayResource>> { return this.session.follow(token, 'mediaRelay', signal); }

  /** Relay credentials can embed several relays; do not assume mediaRelay is a singular link. */
  async mediaRelays(token: ResourceReference, signal?: AbortSignal): Promise<ResourceReference<MediaRelayResource>[]> {
    const embedded = token.data._embedded?.mediaRelay;
    if (embedded !== undefined) {
      const relays = Array.isArray(embedded) ? embedded : [embedded];
      return relays.map((relay) => {
        if (typeof relay !== 'object' || relay === null || Array.isArray(relay)) throw new ProtocolError('An embedded mediaRelay must be a resource object.');
        const data = relay as MediaRelayResource;
        if (!hasLink(data, 'self')) throw new ProtocolError('An embedded mediaRelay must advertise its self link.');
        return resourceReference(data, token.url);
      });
    }
    const relays: ResourceReference<MediaRelayResource>[] = [];
    for (const url of getLinks(token.data, 'mediaRelay', token.url)) relays.push(await this.session.read<MediaRelayResource>(url, signal));
    return relays;
  }
}
